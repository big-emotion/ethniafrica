#!/usr/bin/env node
// Converts the six mapshaper-simplified non-African outlines (see
// src/lib/atlas/assets/README.md § "True-size comparison shapes") into the
// committed worldCompare.ts constant the "true size" game reads at runtime.
// Zero npm dependencies — Node `fs` only, same convention as
// src/lib/atlas/assets/generate-admin0.mjs.
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const [, , inDir, outTsPath] = process.argv;
if (!inDir || !outTsPath) {
  console.error(
    "usage: node generate-world-compare.mjs <simplified-geojson-dir> <out.ts>"
  );
  process.exit(1);
}

// The comparison set is fixed: these six shapes are what the game holds up
// against Africa. Ids are ISO 3166-1 alpha-3 except EUW, which is a synthetic
// id for the dissolved Western-Europe union (no ISO code covers it).
const SHAPES = {
  BRA: { name: "Brazil", nameFr: "Brésil" },
  CHN: { name: "China", nameFr: "Chine" },
  EUW: { name: "Western Europe", nameFr: "Europe de l'Ouest" },
  GRL: { name: "Greenland", nameFr: "Groenland" },
  IND: { name: "India", nameFr: "Inde" },
  USA: { name: "United States (contiguous)", nameFr: "États-Unis (contigus)" },
};

// Natural Earth 1:50m carries hundreds of pinprick islands — Greenland alone
// contributes dozens. Below this many vertices a ring is a speck at the ~300px
// the game renders at, so it is pure payload weight and gets dropped.
const MIN_RING_POINTS = 8;

const round = (n) => Math.round(n * 100) / 100;

const EARTH_RADIUS_KM = 6371.0088;
const rad = (deg) => (deg * Math.PI) / 180;

/**
 * Spherical-excess area of a closed lon/lat ring, in km². Used only to order
 * rings largest-first — mapshaper emits parts in source order, which for the
 * dissolved EUW union puts Great Britain ahead of the continental mainland.
 */
function ringAreaKm2(ring) {
  let excess = 0;
  for (let i = 0; i < ring.length - 1; i++) {
    const [lon1, lat1] = ring[i];
    const [lon2, lat2] = ring[i + 1];
    excess +=
      (rad(lon2) - rad(lon1)) * (2 + Math.sin(rad(lat1)) + Math.sin(rad(lat2)));
  }
  return Math.abs((excess * EARTH_RADIUS_KM * EARTH_RADIUS_KM) / 2);
}

/** Every ring of a Polygon/MultiPolygon, holes included, as flat arrays. */
function ringsOf(geometry) {
  return geometry.type === "Polygon"
    ? geometry.coordinates
    : geometry.coordinates.flat();
}

/** Rounding to 2 decimals collapses neighbours; a closed ring must survive it. */
function roundRing(ring) {
  const rounded = [];
  for (const [lon, lat] of ring) {
    const point = [round(lon), round(lat)];
    const previous = rounded[rounded.length - 1];
    if (previous && previous[0] === point[0] && previous[1] === point[1]) {
      continue;
    }
    rounded.push(point);
  }
  const first = rounded[0];
  const last = rounded[rounded.length - 1];
  if (first && (first[0] !== last[0] || first[1] !== last[1])) {
    rounded.push([first[0], first[1]]);
  }
  return rounded;
}

const entries = Object.keys(SHAPES)
  .sort()
  .map((id) => {
    const geojson = JSON.parse(
      readFileSync(path.join(inDir, `${id}.geojson`), "utf8")
    );
    // mapshaper's -dissolve drops attributes, so it writes a bare
    // GeometryCollection rather than a FeatureCollection. Accept both.
    const geometries =
      geojson.geometries ?? geojson.features.map((feature) => feature.geometry);
    const rings = geometries
      .flatMap(ringsOf)
      .map(roundRing)
      .filter((ring) => ring.length >= MIN_RING_POINTS)
      .sort((a, b) => ringAreaKm2(b) - ringAreaKm2(a));
    if (rings.length === 0) {
      throw new Error(`${id}: every ring was dropped — check the simplify %`);
    }
    const { name, nameFr } = SHAPES[id];
    return `  ${id}: ${JSON.stringify({ name, nameFr, rings })},`;
  });

const ts = `// Generated by scripts/atlas/generate-world-compare.mjs — do not edit by hand.
// Natural Earth "Admin 0 – Countries", 1:50m Cultural Vectors, public domain.
// The six non-African silhouettes the "true size of Africa" game compares
// against, aggressively simplified: they are judged by eye at ~300px wide, so
// coastline detail below that is wasted payload. See ./README.md for the exact
// mapshaper commands that produce this file's input.
// @req REQ-116
export interface WorldCompareShape {
  name: string;
  nameFr: string;
  /** [lon, lat] rings, largest landmass first — one polygon per landmass. */
  rings: [number, number][][];
}

// @req REQ-116
export const WORLD_COMPARE: Record<string, WorldCompareShape> = {
${entries.join("\n")}
};
`;

writeFileSync(outTsPath, ts, "utf8");
console.log(`wrote ${outTsPath} (${entries.length} shapes)`);
