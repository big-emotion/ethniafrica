#!/usr/bin/env node
// Converts a simplified Africa GeoJSON (see README.md step 2) into the
// committed africa-basemap.svg. Zero npm dependencies — Node `fs` only.
//
// AFRICA_GEO_BOUNDS/projectLonLat below are intentionally a plain-JS copy of
// src/lib/atlas/projection.ts: this script must run standalone (before the
// asset it produces exists, and without a TypeScript toolchain) yet stay
// byte-for-byte consistent with the app's projection. If you change the
// bounds or the formula, update both files — projection.test.ts asserts the
// SVG's viewBox stays in sync with BASEMAP_VIEWBOX.
import { readFileSync, writeFileSync } from "node:fs";

const AFRICA_GEO_BOUNDS = { lonMin: -25, lonMax: 52, latMin: -35, latMax: 38 };
const BASEMAP_VIEWBOX = {
  width: 800,
  height: Math.round(
    (800 * (AFRICA_GEO_BOUNDS.latMax - AFRICA_GEO_BOUNDS.latMin)) /
      (AFRICA_GEO_BOUNDS.lonMax - AFRICA_GEO_BOUNDS.lonMin)
  ),
};

function projectLonLat(lon, lat, viewport) {
  const { lonMin, lonMax, latMin, latMax } = AFRICA_GEO_BOUNDS;
  const x = ((lon - lonMin) / (lonMax - lonMin)) * viewport.width;
  const y = ((latMax - lat) / (latMax - latMin)) * viewport.height;
  return { x, y };
}

const round = (n) => Math.round(n * 10) / 10;

const [, , inPath, outPath, outTsPath] = process.argv;
if (!inPath || !outPath || !outTsPath) {
  console.error(
    "usage: node generate-basemap.mjs <simplified.geojson> <out.svg> <out.ts>"
  );
  process.exit(1);
}

const geojson = JSON.parse(readFileSync(inPath, "utf8"));
const geometry =
  geojson.type === "GeometryCollection" ? geojson.geometries[0] : geojson;

if (geometry.type !== "MultiPolygon") {
  throw new Error(`Expected a dissolved MultiPolygon, got ${geometry.type}`);
}

const subpaths = geometry.coordinates.flatMap((polygon) =>
  polygon.map((ring) => {
    const points = ring.map(([lon, lat]) => {
      const { x, y } = projectLonLat(lon, lat, BASEMAP_VIEWBOX);
      return `${round(x)},${round(y)}`;
    });
    return `M${points.join("L")}Z`;
  })
);

const d = subpaths.join(" ");

const svg = `<svg viewBox="0 0 ${BASEMAP_VIEWBOX.width} ${BASEMAP_VIEWBOX.height}" xmlns="http://www.w3.org/2000/svg">
  <path id="africa-landmass" d="${d}" />
</svg>
`;

// The .svg file is the committed, reviewable asset (AC1). The .ts module is
// a generated, bundler-safe companion: Storybook and the Next.js client
// bundle can't `fs.readFileSync` at module scope (no Node builtins in a
// browser bundle), so AfricaBasemap.tsx imports this constant instead of
// reading the .svg file at runtime. Both are written from the same `d`
// string in the same run, so they cannot drift apart.
const ts = `// Generated by generate-basemap.mjs from africa-basemap.svg — do not edit by hand.
// @req REQ-101
export const AFRICA_LANDMASS_PATH =
  "${d}";
`;

writeFileSync(outPath, svg, "utf8");
writeFileSync(outTsPath, ts, "utf8");
console.log(
  `wrote ${outPath} (${Buffer.byteLength(svg, "utf8")} bytes, viewBox 0 0 ${BASEMAP_VIEWBOX.width} ${BASEMAP_VIEWBOX.height})`
);
console.log(`wrote ${outTsPath}`);
