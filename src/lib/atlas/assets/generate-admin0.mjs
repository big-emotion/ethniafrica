#!/usr/bin/env node
// Converts the reviewed mockups' admin-0 geometry (docs/design/mockups/parts/
// africa-admin0.json — Natural Earth "Admin 0 – Countries", 1:50m, the same
// dataset africa-basemap.svg is dissolved from, see ./README.md) into the
// committed africaAdmin0.ts constant AtlasGlobe overlays read at runtime.
// Zero npm dependencies — Node `fs` only, same convention as
// generate-basemap.mjs.
import { readFileSync, writeFileSync } from "node:fs";

const [, , inPath, outTsPath] = process.argv;
if (!inPath || !outTsPath) {
  console.error(
    "usage: node generate-admin0.mjs <africa-admin0.json> <out.ts>"
  );
  process.exit(1);
}

const round = (n) => Math.round(n * 100) / 100;

const source = JSON.parse(readFileSync(inPath, "utf8"));
const countryIds = Object.keys(source).sort();

const entries = countryIds.map((id) => {
  const country = source[id];
  const rings = country.rings.map((ring) =>
    ring.map(([lon, lat]) => [round(lon), round(lat)])
  );
  return `  ${id}: ${JSON.stringify({ name: country.name, nameFr: country.fr, rings })},`;
});

const ts = `// Generated by generate-admin0.mjs from
// docs/design/mockups/parts/africa-admin0.json — do not edit by hand.
// Natural Earth "Admin 0 – Countries", 1:50m Cultural Vectors, public domain
// (see ../assets/README.md for the shared basemap's full provenance notes;
// this is the same dataset, kept per-country instead of dissolved).
// @req REQ-116
export interface Admin0Country {
  name: string;
  nameFr: string;
  /** [lon, lat] rings, outer ring first — one polygon per landmass/enclave. */
  rings: [number, number][][];
}

export const AFRICA_ADMIN0: Record<string, Admin0Country> = {
${entries.join("\n")}
};
`;

writeFileSync(outTsPath, ts, "utf8");
console.log(`wrote ${outTsPath} (${countryIds.length} countries)`);
