#!/usr/bin/env node
// Converts a filtered Natural Earth "Admin 0 – Countries" GeoJSON into the
// committed worldAdmin0.ts constant the Mercator game reads at runtime.
// Zero npm dependencies — Node `fs` only, same convention as
// generate-admin0.mjs, which produces this file's African sibling.
//
// See ./README.md for the mapshaper commands that produce the input and for
// why the country list is an editorial choice rather than a filter.
import { readFileSync, writeFileSync } from "node:fs";

/**
 * How far from its mainland a polygon may sit and still count as the same
 * country, in degrees of lon/lat.
 *
 * Natural Earth's admin-0 France carries Guyane, Mayotte, la Réunion and the
 * Antilles in the same feature. Summed, they answer a question the round is
 * not asking — a reader told « France » and shown a shape over the Atlantic
 * is being shown four shapes — and they cost more payload than the mainland
 * they surround. Twelve degrees keeps Corsica with France, Sicily and
 * Sardinia with Italy and the Hebrides with Britain, and drops the overseas
 * departments, Svalbard and Iceland's far islets.
 *
 * A country whose mainland this rule materially shrinks is renamed for what
 * is left — see NAME_OVERRIDE_FR — because publishing a surface under a name
 * that does not cover it is the one thing this asset must not do.
 */
const MAINLAND_RADIUS_DEGREES = 12;

/**
 * Where the rule above changes what the name means. Only France: its overseas
 * departments are 89 000 km² against a 552 000 km² mainland, and « France »
 * unqualified would be 14 % short of the figure a reader looks up.
 */
const NAME_OVERRIDE_FR = {
  FRA: "France métropolitaine",
};

const NAME_OVERRIDE_EN = {
  FRA: "Metropolitan France",
};

const [, , inPath, outTsPath] = process.argv;
if (!inPath || !outTsPath) {
  console.error(
    "usage: node generate-world-admin0.mjs <world-simplified.geojson> <out.ts>"
  );
  process.exit(1);
}

const round = (n) => Math.round(n * 100) / 100;

const centroidOf = (ring) => {
  const lon = ring.reduce((sum, point) => sum + point[0], 0) / ring.length;
  const lat = ring.reduce((sum, point) => sum + point[1], 0) / ring.length;
  return [lon, lat];
};

const source = JSON.parse(readFileSync(inPath, "utf8"));

const countries = source.features
  .map((feature) => {
    const polygons =
      feature.geometry.type === "Polygon"
        ? [feature.geometry.coordinates]
        : feature.geometry.coordinates;

    // Outer rings only: a hole would subtract from an area the game states,
    // and no country in this list has one worth a kilometre.
    const outers = polygons.map((polygon) => polygon[0]);
    const mainland = outers.reduce((largest, ring) =>
      ring.length > largest.length ? ring : largest
    );
    const [mainLon, mainLat] = centroidOf(mainland);

    const kept = outers.filter((ring) => {
      const [lon, lat] = centroidOf(ring);
      return (
        Math.hypot(lon - mainLon, lat - mainLat) <= MAINLAND_RADIUS_DEGREES
      );
    });

    const { id, name, fr } = feature.properties;
    return {
      id,
      name: NAME_OVERRIDE_EN[id] ?? name,
      nameFr: NAME_OVERRIDE_FR[id] ?? fr,
      rings: kept.map((ring) =>
        ring.map(([lon, lat]) => [round(lon), round(lat)])
      ),
      droppedRings: outers.length - kept.length,
    };
  })
  .sort((a, b) => a.id.localeCompare(b.id));

const entries = countries.map(
  ({ id, name, nameFr, rings }) =>
    `  ${id}: ${JSON.stringify({ name, nameFr, rings })},`
);

const ts = `// Generated by generate-world-admin0.mjs — do not edit by hand.
// Natural Earth "Admin 0 – Countries", 1:50m Cultural Vectors, public domain
// (see ./README.md for the full provenance notes and the exact commands).
//
// The countries outside Africa that the Mercator game may put on a button.
// Deliberately disjoint from WORLD_COMPARE, which holds the shapes the
// estimate round measures Africa against: two assets naming one country would
// let the same reveal state two areas for it. \`territory.ts\` reads both and
// \`territory.test.ts\` asserts the key sets never overlap.
//
// Islands beyond MAINLAND_RADIUS_DEGREES of the mainland are dropped, so the
// shape drawn on the globe is the shape the option names.
// @req REQ-120
import type { Admin0Country } from "@/lib/atlas/assets/africaAdmin0";

// @req REQ-120
export const WORLD_ADMIN0: Record<string, Admin0Country> = {
${entries.join("\n")}
};
`;

writeFileSync(outTsPath, ts, "utf8");

console.log(`wrote ${outTsPath} (${countries.length} countries)`);
for (const country of countries) {
  if (country.droppedRings > 0) {
    console.log(
      `  ${country.id} ${country.nameFr}: kept ${country.rings.length} rings, dropped ${country.droppedRings}`
    );
  }
}
